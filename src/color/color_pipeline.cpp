static cmsHPROFILE linearProfile(cmsCIExyYTRIPLE primaries) {
    cmsCIExyY white{0.3127,0.3290,1};
    auto *curve=cmsBuildGamma(nullptr,1);
    if(!curve)return nullptr;
    cmsToneCurve *curves[]{curve,curve,curve};
    auto profile=cmsCreateRGBProfile(&white,&primaries,curves);
    cmsFreeToneCurve(curve); return profile;
}
cmsHPROFILE workProfile() { return linearProfile({{0.708,0.292,1},{0.170,0.797,1},{0.131,0.046,1}}); }
cmsHPROFILE linearSrgbProfile() { return linearProfile({{0.64,0.33,1},{0.30,0.60,1},{0.15,0.06,1}}); }
QImage inputToWork(const QImage &image,const QByteArray &icc,QString &error,const CancellationToken &cancel) {
    error.clear();
    if(isCanceled(cancel)){error="Canceled";return {};}
    auto input=icc.isEmpty()?cmsCreate_sRGBProfile():cmsOpenProfileFromMem(icc.constData(),cmsUInt32Number(icc.size()));
    auto work=workProfile();
    if(!input || !work || cmsGetColorSpace(input)!=cmsSigRgbData) {
        if(input) cmsCloseProfile(input); if(work) cmsCloseProfile(work);
        error=QStringLiteral("不支持或损坏的 RGB ICC"); return {};
    }
    auto transform=cmsCreateTransform(input,TYPE_RGBA_8,work,TYPE_RGBA_FLT,INTENT_RELATIVE_COLORIMETRIC,cmsFLAGS_COPY_ALPHA|cmsFLAGS_NOOPTIMIZE|cmsFLAGS_NOCACHE);
    const int workers=image.width()*qint64(image.height())>=1024*1024?std::clamp(QThread::idealThreadCount(),1,std::min(6,image.height())):1;
    std::array<cmsHTRANSFORM,6> transforms{};transforms[0]=transform;
    if(transform)for(int i=1;i<workers;++i){transforms[i]=cmsCreateTransform(input,TYPE_RGBA_8,work,TYPE_RGBA_FLT,INTENT_RELATIVE_COLORIMETRIC,cmsFLAGS_COPY_ALPHA|cmsFLAGS_NOOPTIMIZE|cmsFLAGS_NOCACHE);if(!transforms[i]){for(auto t:transforms)if(t)cmsDeleteTransform(t);cmsCloseProfile(input);cmsCloseProfile(work);error="ICC worker transform allocation";return {};}}
    cmsCloseProfile(input); cmsCloseProfile(work);
    if(!transform) {error=QStringLiteral("ICC 输入变换失败");return {};}
    QImage encoded=image.convertToFormat(QImage::Format_RGBA8888);
    QImage result(image.size(),QImage::Format_RGBA32FPx4);
    if(result.isNull()||encoded.isNull()) {for(auto t:transforms)if(t)cmsDeleteTransform(t); error=QStringLiteral("工作图像分配失败");return {};}
    auto *output=result.bits();const auto *source=encoded.constBits();const auto inStride=encoded.bytesPerLine(),outStride=result.bytesPerLine();
    const auto rows=[&](int part){for(int y=result.height()*part/workers;y<result.height()*(part+1)/workers;++y){if(isCanceled(cancel))return;cmsDoTransform(transforms[part],source+y*inStride,output+y*outStride,cmsUInt32Number(result.width()));}};
    if(workers==1)rows(0);else{static QThreadPool pool;pool.setMaxThreadCount(6);QFuture<void> jobs[6];for(int i=0;i<workers;++i)jobs[i]=QtConcurrent::run(&pool,[&,i]{rows(i);});for(int i=0;i<workers;++i)jobs[i].waitForFinished();}
    for(auto t:transforms)if(t)cmsDeleteTransform(t);if(isCanceled(cancel)){error="Canceled";return {};}return result;
}
QImage workToSrgbReference(const QImage &linear,QString &error) {
    error.clear();
    auto input=workProfile(); auto output=cmsCreate_sRGBProfile();
    if(!input||!output){if(input)cmsCloseProfile(input);if(output)cmsCloseProfile(output);error="ICC profile allocation";return {};}
    auto transform=cmsCreateTransform(input,TYPE_RGBA_FLT,output,TYPE_RGBA_8,INTENT_RELATIVE_COLORIMETRIC,cmsFLAGS_COPY_ALPHA|cmsFLAGS_NOOPTIMIZE|cmsFLAGS_NOCACHE);
    cmsCloseProfile(input); cmsCloseProfile(output);
    if(!transform) {error=QStringLiteral("sRGB 显示变换失败");return {};}
    QImage result(linear.size(),QImage::Format_RGBA8888);
    if(result.isNull()){cmsDeleteTransform(transform);error=QStringLiteral("显示图分配失败");return {};}
    for(int y=0;y<linear.height();++y) cmsDoTransform(transform,linear.constScanLine(y),result.scanLine(y),cmsUInt32Number(linear.width()));
    cmsDeleteTransform(transform); result.setColorSpace(QColorSpace::SRgb); return result;
}
// Fixed SDR sRGB path: matrix and 16-bit lookup are generated by Little CMS.
// Arbitrary input ICC still uses the full input transform above.
QImage workToSrgbAffine(const QImage &linear,const std::array<float,9> &edit,const std::array<float,3> &offset,QString &error,const ToneOperator *tone,const PostCropVignette *vignette,bool flipHorizontal,bool flipVertical,const ProceduralGrain *grain,const CancellationToken &cancel) {
    if(isCanceled(cancel)){error="Canceled";return {};}
    struct DisplayTables {
        std::array<float,9> matrix{};std::array<quint8,65536> encoding{};bool valid=false;
        DisplayTables(){
            auto work=workProfile(),srgbLinear=linearSrgbProfile(),srgb=cmsCreate_sRGBProfile();
            if(!work||!srgbLinear||!srgb)return;
            auto m=cmsCreateTransform(work,TYPE_RGB_FLT,srgbLinear,TYPE_RGB_FLT,INTENT_RELATIVE_COLORIMETRIC,cmsFLAGS_NOOPTIMIZE|cmsFLAGS_NOCACHE);
            auto e=cmsCreateTransform(srgbLinear,TYPE_RGB_FLT,srgb,TYPE_RGB_8,INTENT_RELATIVE_COLORIMETRIC,cmsFLAGS_NOOPTIMIZE|cmsFLAGS_NOCACHE);
            if(m&&e){const float basis[]{1,0,0,0,1,0,0,0,1};float output[9];cmsDoTransform(m,basis,output,3);
                for(int c=0;c<3;++c)for(int j=0;j<3;++j)matrix[c*3+j]=output[j*3+c];
                std::vector<float> ramp(65536*3);std::vector<quint8> encoded(65536*3);
                for(int i=0;i<65536;++i)for(int c=0;c<3;++c)ramp[i*3+c]=float(i)/65535;
                cmsDoTransform(e,ramp.data(),encoded.data(),65536);for(int i=0;i<65536;++i)encoding[i]=encoded[i*3];valid=true;
            }
            if(m)cmsDeleteTransform(m);if(e)cmsDeleteTransform(e);cmsCloseProfile(work);cmsCloseProfile(srgbLinear);cmsCloseProfile(srgb);
        }
    };
    static const DisplayTables tables;error.clear();
    for(float v:edit)if(!std::isfinite(v)){error="Nonfinite color matrix";return {};}
    for(float v:offset)if(!std::isfinite(v)){error="Nonfinite color offset";return {};}
    if(!tables.valid||linear.isNull()||linear.format()!=QImage::Format_RGBA32FPx4){error="Invalid SDR transform/frame";return {};}
    QImage result(linear.size(),QImage::Format_RGBA8888);if(result.isNull()){error="SDR allocation";return {};}
    constexpr int workers=6;
    static QThreadPool pool;pool.setMaxThreadCount(workers);QFuture<void> jobs[workers];
    // Detach once; threads write disjoint rows using the stable buffer pointers.
    auto *destination=result.bits();const auto *source=linear.constBits();const auto inStride=linear.bytesPerLine(),outStride=result.bytesPerLine();
    std::array<float,9> matrix{};std::array<float,3> translation{};std::atomic<bool> invalid{false};
    for(int c=0;c<3;++c){for(int j=0;j<3;++j)for(int k=0;k<3;++k)matrix[c*3+j]+=tables.matrix[c*3+k]*edit[k*3+j];for(int k=0;k<3;++k)translation[c]+=tables.matrix[c*3+k]*offset[k];}
    for(int part=0;part<workers;++part)jobs[part]=QtConcurrent::run(&pool,[&,part]{
        for(int y=linear.height()*part/workers;y<linear.height()*(part+1)/workers;++y){if(isCanceled(cancel))return;auto *out=destination+y*outStride;const auto *in=reinterpret_cast<const float *>(source+(flipVertical?linear.height()-1-y:y)*inStride);
            for(int x=0;x<linear.width();++x){const auto *pixel=in+(flipHorizontal?linear.width()-1-x:x)*4;for(int c=0;c<4;++c)if(!std::isfinite(pixel[c])){invalid=true;return;}
                const float alpha=std::clamp(pixel[3],0.f,1.f);
                if(alpha<=1e-8f){out[x*4]=out[x*4+1]=out[x*4+2]=0;out[x*4+3]=quint8(alpha*255+.5f);continue;}
                float adjusted[3]{};
                if(tone||vignette||grain){for(int c=0;c<3;++c)adjusted[c]=edit[c*3]*pixel[0]+edit[c*3+1]*pixel[1]+edit[c*3+2]*pixel[2]+offset[c];if(tone)tone->apply(adjusted);if(vignette)vignette->apply(adjusted,x,y);if(grain)grain->apply(adjusted,x,y);}
                for(int c=0;c<3;++c){const float v=(tone||vignette||grain)?tables.matrix[c*3]*adjusted[0]+tables.matrix[c*3+1]*adjusted[1]+tables.matrix[c*3+2]*adjusted[2]:matrix[c*3]*pixel[0]+matrix[c*3+1]*pixel[1]+matrix[c*3+2]*pixel[2]+translation[c];if(!std::isfinite(v)){invalid=true;return;}out[x*4+c]=alpha>1e-8f?tables.encoding[size_t(std::clamp(v,0.f,1.f)*65535+.5f)]:0;}
                out[x*4+3]=quint8(alpha*255+.5f);}
        }
    });
    for(auto &job:jobs)job.waitForFinished();if(isCanceled(cancel)){error="Canceled";return {};}if(invalid){error="NaN/Inf source";return {};}result.setColorSpace(QColorSpace::SRgb);return result;
}
QImage workToSrgb(const QImage &linear,QString &error,const CancellationToken &cancel){return workToSrgbAffine(linear,{1,0,0,0,1,0,0,0,1},{0,0,0},error,nullptr,nullptr,false,false,nullptr,cancel);}
