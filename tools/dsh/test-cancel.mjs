import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('./bridge.mjs', import.meta.url), 'utf8');
const fn = source.match(/function cancelSession\(sessionId\) \{[\s\S]*?\n\}/)?.[0];
assert.ok(fn, 'cancellation helper exists');
assert.equal(/rpc\('session\/cancel'/.test(source), false, 'cancel is never a request');
const packets = [];
const context = { child: { stdin: { writable: true, destroyed: false } }, write: packet => packets.push(packet) };
vm.createContext(context);
vm.runInContext(`${fn}; cancelSession('test-session');`, context);
assert.equal(packets.length, 1);
assert.equal(JSON.stringify(packets[0]), JSON.stringify({ jsonrpc: '2.0', method: 'session/cancel', params: { sessionId: 'test-session' } }));
assert.equal(Object.hasOwn(packets[0], 'id'), false);
context.child.stdin.destroyed = true;
vm.runInContext("cancelSession('closed');", context);
assert.equal(packets.length, 1, 'closed transport gets no write');
context.child = undefined;
vm.runInContext("cancelSession('missing');", context);
assert.equal(packets.length, 1);
process.stdout.write('ACP cancellation notification checks passed.\n');
